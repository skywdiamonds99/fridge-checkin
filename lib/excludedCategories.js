// PRD 4장 61~63줄 — 등록하지 않는 비식료품 카테고리.
// 기준표(referenceTable)보다 먼저 확인해서, "기준표에 없다"는 이유로
// 이 품목들이 확인 필요로 올라가 사용자가 실수로 등록하는 일을 막는다.
const EXCLUDED_PATTERNS = [
  /원두|드립백|핸드드립/, // 커피 원두
  /티백|녹차|홍차|보이차|우롱차|둥굴레차|메밀차/, // 차
  /후추|고춧가루|계피|월계수잎|향신료|파슬리가루|카레가루/, // 향신료 (카레 완제품 아님, 가루만)
  /영양제|비타민|유산균|프로바이오틱스|건강기능식품|홍삼|오메가3/, // 영양제·건강기능식품
  /사료|간식캔|츄르|고양이|강아지용/, // 반려동물 사료·간식
  /세제|섬유유연제|봉투|쓰레기봉투|휴지|물티슈|샴푸|린스|세정제|주방세제|수세미/, // 세제·봉투·생활용품
];

export function isExcludedCategory(name) {
  const text = name || "";
  return EXCLUDED_PATTERNS.some((pattern) => pattern.test(text));
}
